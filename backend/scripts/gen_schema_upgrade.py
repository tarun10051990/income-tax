#!/usr/bin/env python3
"""Generates db/mysql/schema_upgrade.sql from db/mysql/schema.sql.

The upgrade script is safe to run on an empty or an existing database: it creates
missing tables, adds missing columns / indexes / unique keys / foreign keys, and
widens enum or text columns that are too small. It never drops tables, columns or data.

    python3 backend/scripts/gen_schema_upgrade.py
"""
import pathlib
import re

DIR = pathlib.Path(__file__).resolve().parent.parent / "src/main/resources/db/mysql"
SCHEMA = (DIR / "schema.sql").read_text()

TABLE_RE = re.compile(r"CREATE TABLE (\w+) \((.*?)\n\) (ENGINE=[^;]*);", re.S)
INDEX_RE = re.compile(r"^create index (\w+) on (\w+) \(([^)]*)\);$", re.M)
UNIQUE_RE = re.compile(r"^alter table (\w+) add constraint (\w+) unique \(([^)]*)\);$", re.M)
FK_RE = re.compile(
    r"^alter table (\w+) add constraint (\w+) foreign key \(([^)]*)\) references (\w+) \(([^)]*)\);$", re.M)


def q(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "''") + "'"


def cols(s: str) -> str:
    return ",".join(c.strip() for c in s.split(","))


def kind(col_type: str) -> str:
    t = col_type.lower()
    if t.startswith("enum"):
        return "enum"
    if t.startswith("varchar") or t in ("text", "longtext"):
        return "text"
    return "other"


def text_length(col_type: str) -> int:
    t = col_type.lower()
    m = re.match(r"varchar\((\d+)\)", t)
    if m:
        return int(m.group(1))
    return {"text": 65535, "longtext": 4294967295}.get(t, 0)


def fill_value(col_type: str) -> str:
    """Value given to existing rows when a NOT NULL column is added (others use MySQL's implicit default)."""
    t = col_type.lower()
    m = re.match(r"datetime(\((\d)\))?$", t)
    if m:
        return f"CURRENT_TIMESTAMP({m.group(2) or ''})".replace("()", "")
    if t == "date":
        return "(CURRENT_DATE)"
    return ""


tables = TABLE_RE.findall(SCHEMA)
out = [
    "-- TaxFilr: create OR upgrade the MySQL 8 schema (generated by backend/scripts/gen_schema_upgrade.py from schema.sql).",
    "-- Safe to run on an empty database or on one where some tables already exist, and safe to run again.",
    "-- It only ADDS what is missing (tables, columns, indexes, unique keys, foreign keys) and widens enum/text",
    "-- columns that are too small. It never drops a table, column or row.",
    "--   mysql -u root -p < backend/src/main/resources/db/mysql/schema_upgrade.sql",
    "-- Take a backup first:  mysqldump -u root -p taxfilr > taxfilr_backup.sql",
    "",
    "CREATE DATABASE IF NOT EXISTS taxfilr CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;",
    "USE taxfilr;",
    "",
    "SET @old_fk_checks = @@FOREIGN_KEY_CHECKS;",
    "SET FOREIGN_KEY_CHECKS = 0;",
    "",
    "DROP PROCEDURE IF EXISTS tf_sync_column;",
    "DROP PROCEDURE IF EXISTS tf_add_index;",
    "DROP PROCEDURE IF EXISTS tf_add_fk;",
    "DELIMITER //",
    """CREATE PROCEDURE tf_sync_column(IN p_table VARCHAR(64), IN p_column VARCHAR(64), IN p_definition TEXT,
                                IN p_kind VARCHAR(8), IN p_type TEXT, IN p_length BIGINT, IN p_fill TEXT)
BEGIN
    DECLARE v_type TEXT;
    DECLARE v_length BIGINT;
    SELECT LOWER(REPLACE(COLUMN_TYPE, ' ', '')), CHARACTER_MAXIMUM_LENGTH INTO v_type, v_length
      FROM information_schema.COLUMNS
     WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = p_table AND COLUMN_NAME = p_column;
    IF v_type IS NULL AND p_fill <> '' THEN
        -- Existing rows need a value for a new NOT NULL date column; the temporary default is removed below.
        SET @tf_sql = CONCAT('ALTER TABLE `', p_table, '` ADD COLUMN ', p_definition, ' DEFAULT ', p_fill);
        PREPARE tf_stmt FROM @tf_sql;
        EXECUTE tf_stmt;
        DEALLOCATE PREPARE tf_stmt;
        SET @tf_sql = CONCAT('ALTER TABLE `', p_table, '` ALTER COLUMN `', p_column, '` DROP DEFAULT');
    ELSEIF v_type IS NULL THEN
        SET @tf_sql = CONCAT('ALTER TABLE `', p_table, '` ADD COLUMN ', p_definition);
    ELSEIF (p_kind = 'enum' AND v_type <> p_type) OR (p_kind = 'text' AND v_length < p_length) THEN
        SET @tf_sql = CONCAT('ALTER TABLE `', p_table, '` MODIFY COLUMN ', p_definition);
    ELSE
        SET @tf_sql = NULL;
    END IF;
    IF @tf_sql IS NOT NULL THEN
        PREPARE tf_stmt FROM @tf_sql;
        EXECUTE tf_stmt;
        DEALLOCATE PREPARE tf_stmt;
    END IF;
END //""",
    """CREATE PROCEDURE tf_add_index(IN p_table VARCHAR(64), IN p_name VARCHAR(64), IN p_columns TEXT,
                              IN p_unique TINYINT)
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM (
            SELECT INDEX_NAME, NON_UNIQUE, GROUP_CONCAT(COLUMN_NAME ORDER BY SEQ_IN_INDEX) AS cols
              FROM information_schema.STATISTICS
             WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = p_table
             GROUP BY INDEX_NAME, NON_UNIQUE) i
         WHERE i.INDEX_NAME = p_name OR (i.cols = p_columns AND (p_unique = 0 OR i.NON_UNIQUE = 0))) THEN
        SET @tf_sql = IF(p_unique = 1,
            CONCAT('ALTER TABLE `', p_table, '` ADD CONSTRAINT `', p_name, '` UNIQUE (', p_columns, ')'),
            CONCAT('CREATE INDEX `', p_name, '` ON `', p_table, '` (', p_columns, ')'));
        PREPARE tf_stmt FROM @tf_sql;
        EXECUTE tf_stmt;
        DEALLOCATE PREPARE tf_stmt;
    END IF;
END //""",
    """CREATE PROCEDURE tf_add_fk(IN p_table VARCHAR(64), IN p_name VARCHAR(64), IN p_column VARCHAR(64),
                           IN p_ref_table VARCHAR(64), IN p_ref_column VARCHAR(64))
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.KEY_COLUMN_USAGE
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = p_table
           AND REFERENCED_TABLE_NAME IS NOT NULL
           AND (CONSTRAINT_NAME = p_name
                OR (COLUMN_NAME = p_column AND REFERENCED_TABLE_NAME = p_ref_table
                    AND REFERENCED_COLUMN_NAME = p_ref_column))) THEN
        SET @tf_sql = CONCAT('ALTER TABLE `', p_table, '` ADD CONSTRAINT `', p_name, '` FOREIGN KEY (`', p_column,
                             '`) REFERENCES `', p_ref_table, '` (`', p_ref_column, '`)');
        PREPARE tf_stmt FROM @tf_sql;
        EXECUTE tf_stmt;
        DEALLOCATE PREPARE tf_stmt;
    END IF;
END //""",
    "DELIMITER ;",
    "",
]

for name, body, engine in tables:
    lines = [l.strip().rstrip(",") for l in body.strip().split("\n")]
    out.append(f"-- Table: {name}")
    out.append(f"CREATE TABLE IF NOT EXISTS {name} (\n    " + ",\n    ".join(lines) + f"\n) {engine};")
    for line in lines:
        if line.lower().startswith("primary key"):
            continue
        col, col_type = line.split(" ", 1)
        not_null = col_type.lower().endswith(" not null")
        col_type = re.sub(r"\s+not null$", "", col_type, flags=re.I)
        fill = fill_value(col_type) if not_null else ""
        k = kind(col_type)
        norm = col_type.lower().replace(" ", "") if k == "enum" else ""
        out.append(f"CALL tf_sync_column({q(name)}, {q(col)}, {q(line)}, {q(k)}, {q(norm)}, {text_length(col_type)}, {q(fill)});")
    out.append("")

out.append("-- Indexes and unique keys (skipped when an index with the same name or columns already exists)")
for idx, table, c in INDEX_RE.findall(SCHEMA):
    out.append(f"CALL tf_add_index({q(table)}, {q(idx)}, {q(cols(c))}, 0);")
for table, idx, c in UNIQUE_RE.findall(SCHEMA):
    out.append(f"CALL tf_add_index({q(table)}, {q(idx)}, {q(cols(c))}, 1);")
out.append("")
out.append("-- Foreign keys (skipped when the same link already exists)")
for table, fk, c, ref, rc in FK_RE.findall(SCHEMA):
    out.append(f"CALL tf_add_fk({q(table)}, {q(fk)}, {q(c.strip())}, {q(ref)}, {q(rc.strip())});")

out += [
    "",
    "DROP PROCEDURE IF EXISTS tf_sync_column;",
    "DROP PROCEDURE IF EXISTS tf_add_index;",
    "DROP PROCEDURE IF EXISTS tf_add_fk;",
    "SET FOREIGN_KEY_CHECKS = @old_fk_checks;",
    "",
]

statements = len(INDEX_RE.findall(SCHEMA)) + len(UNIQUE_RE.findall(SCHEMA)) + len(FK_RE.findall(SCHEMA))
assert statements == SCHEMA.count("\ncreate index") + SCHEMA.count("\nalter table"), "unparsed constraint in schema.sql"
(DIR / "schema_upgrade.sql").write_text("\n".join(out))
print(f"{len(tables)} tables, {statements} indexes/keys -> {DIR / 'schema_upgrade.sql'}")
