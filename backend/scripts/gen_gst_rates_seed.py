#!/usr/bin/env python3
"""Generates db/mysql/gst_rates_seed.sql from seed/gst-rates.json.

Each row is only inserted when no row with the same code and start date exists, so the script can be re-run
and never overwrites rates an admin has edited. Items whose rate changed on GST 2.0 (rateChangeDate) get two
rows: the old rate up to the day before, and the new rate from that date.

    python3 backend/scripts/gen_gst_rates_seed.py
"""
import datetime
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent / "src/main/resources"
DATA = json.loads((ROOT / "seed/gst-rates.json").read_text())


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


def insert(table, row):
    cols = list(row)
    values = ", ".join(sql(row[c]) for c in cols)
    names = ", ".join(cols)
    return (f"INSERT INTO {table} (id, {names}, active, updated_by, updated_at)\n"
            f"SELECT UUID(), {values}, 1, 'system', NOW(6) FROM DUAL\n"
            f"WHERE NOT EXISTS (SELECT 1 FROM {table} WHERE code = {sql(row['code'])} "
            f"AND effective_from = {sql(row['effective_from'])});")


change = datetime.date.fromisoformat(DATA["rateChangeDate"])
out = ["-- GST rates and rules for TaxFilr (generated by backend/scripts/gen_gst_rates_seed.py).",
       "-- Safe to re-run: existing rows (including admin edits) are kept. Run after schema_upgrade.sql:",
       "--   mysql -u root -p taxfilr < backend/src/main/resources/db/mysql/gst_rates_seed.sql",
       "-- Rates follow GST Council decisions incl. GST 2.0 (22 Sep 2025); have a tax expert confirm them.",
       "USE taxfilr;", ""]
for c in DATA["categories"]:
    base = dict(code=c["code"], business_type=c["businessType"], kind=c["kind"], hsn_sac=c["hsnSac"],
                name=c["name"], hint=c["hint"], treatment=c["treatment"], rate=c["rate"], cess_rate=c["cessRate"],
                reverse_charge=c["reverseCharge"], itc_allowed=c["itcAllowed"], effective_from=c["effectiveFrom"],
                effective_to=None, sort_order=c["sortOrder"])
    before = c.get("before")
    if before:
        old = dict(base, hint=None, cess_rate=before.get("cessRate"),
                   effective_to=(change - datetime.timedelta(days=1)).isoformat())
        for k, col in (("rate", "rate"), ("treatment", "treatment"), ("itcAllowed", "itc_allowed")):
            if k in before:
                old[col] = before[k]
        out.append(insert("gst_rate_categories", old))
        base["effective_from"] = change.isoformat()
    out.append(insert("gst_rate_categories", base))
out.append("")
for r in DATA["rules"]:
    out.append(insert("gst_rules", dict(
        code=r["code"], kind=r["kind"], section=r["section"], name=r["name"], hint=r["hint"], rate=r["rate"],
        amount=r["amount"], special_state_amount=r["specialStateAmount"], max_amount=r["maxAmount"], itc=r["itc"],
        effective_from=r["effectiveFrom"], effective_to=r["effectiveTo"], sort_order=r["sortOrder"])))
(ROOT / "db/mysql/gst_rates_seed.sql").write_text("\n".join(out) + "\n")
print(f"wrote {len(out)} lines")
