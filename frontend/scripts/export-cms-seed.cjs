#!/usr/bin/env node
/*
 * Generates SQL that inserts every bundled default content entry (marketing pages, field guides,
 * portal text, ...) into `cms_entries` as PUBLISHED rows. Re-run after editing src/content/*.
 *
 *   node scripts/export-cms-seed.cjs            -> writes ../backend/src/main/resources/db/mysql/cms_seed.sql
 *   node scripts/export-cms-seed.cjs --json     -> also writes cms_seed.json (POST /api/admin/cms/import body)
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const Module = require("module");
const { execFileSync } = require("child_process");
const { randomUUID } = require("crypto");

const frontendDir = path.resolve(__dirname, "..");
const outDir = fs.mkdtempSync(path.join(os.tmpdir(), "cms-seed-"));
const sqlTarget = path.resolve(frontendDir, "../backend/src/main/resources/db/mysql/cms_seed.sql");
const jsonTarget = path.resolve(frontendDir, "../backend/src/main/resources/db/cms_seed.json");

const sources = [
  "src/lib/site-content.ts",
  ...fs.readdirSync(path.join(frontendDir, "src/content")).filter((f) => f.endsWith(".ts")).map((f) => `src/content/${f}`),
];

// Strips types only; the real type-check is `next build`. Unresolved "@/..." type imports are expected here.
try {
  execFileSync(
    path.join(frontendDir, "node_modules/typescript/bin/tsc"),
    [
      ...sources,
      "--outDir", outDir, "--rootDir", path.join(frontendDir, "src"),
      "--module", "commonjs", "--target", "es2020", "--moduleResolution", "node",
      "--skipLibCheck", "--noResolve", "--isolatedModules", "--noEmitOnError", "false",
    ],
    { cwd: frontendDir, stdio: "ignore" },
  );
} catch {
  // tsc exits non-zero on type errors but still emits JS.
}
if (!fs.existsSync(path.join(outDir, "lib/site-content.js"))) {
  throw new Error("tsc did not emit lib/site-content.js");
}

const originalResolve = Module._resolveFilename;
Module._resolveFilename = function (request, ...rest) {
  if (request.startsWith("@/")) request = path.join(outDir, request.slice(2));
  return originalResolve.call(this, request, ...rest);
};

const { defaultImportPayload } = require(path.join(outDir, "lib/site-content.js"));
const payload = defaultImportPayload();

const escape = (value) => `'${String(value).replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;
const lines = [
  "-- Default website content for the `cms_entries` table (MySQL 8).",
  "-- Generated by frontend/scripts/export-cms-seed.cjs — do not edit by hand, edit frontend/src/content/* and re-run.",
  "-- Safe to re-run: existing (collection, slug) rows are left untouched.",
  "",
  "SET NAMES utf8mb4;",
  "",
];
let total = 0;
for (const [collection, entries] of Object.entries(payload)) {
  lines.push(`-- ${collection} (${entries.length})`);
  entries.forEach((entry, index) => {
    total += 1;
    lines.push(
      "INSERT IGNORE INTO cms_entries (id, collection, slug, title, status, sort_order, data, version, updated_by, created_at, updated_at, published_at)",
      `VALUES (${escape(randomUUID())}, ${escape(collection)}, ${escape(entry.slug)}, ${entry.title ? escape(entry.title) : "NULL"}, 'PUBLISHED', ${index}, ${escape(JSON.stringify(entry.data))}, 1, 'seed', NOW(6), NOW(6), NOW(6));`,
    );
  });
  lines.push("");
}
lines.push(`-- ${total} rows`);
fs.writeFileSync(sqlTarget, lines.join("\n") + "\n");
console.log(`wrote ${total} rows to ${path.relative(process.cwd(), sqlTarget)}`);

if (process.argv.includes("--json")) {
  fs.writeFileSync(jsonTarget, JSON.stringify({ collections: payload, publish: true }, null, 2) + "\n");
  console.log(`wrote ${path.relative(process.cwd(), jsonTarget)}`);
}
fs.rmSync(outDir, { recursive: true, force: true });
